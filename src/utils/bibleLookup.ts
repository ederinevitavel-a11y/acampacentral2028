/**
 * Normalizes user input for matching (removes excess whitespace, accents, lowercase)
 */
export function normalizeVerseRef(ref: string): string {
  return ref
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Searches offline dictionary for instant match
 */
export function lookupOfflineVerse(ref: string): string | null {
  const normalized = normalizeVerseRef(ref);
  if (!normalized) return null;
  
  if (POPULAR_VERSES[normalized]) {
    return POPULAR_VERSES[normalized];
  }

  // Try flexible matching without 's' plural differences (e.g., salmo vs salmos)
  for (const [key, text] of Object.entries(POPULAR_VERSES)) {
    const normKey = normalizeVerseRef(key);
    if (normKey === normalized || normKey.replace('salmos', 'salmo') === normalized.replace('salmos', 'salmo')) {
      return text;
    }
  }

  return null;
}

