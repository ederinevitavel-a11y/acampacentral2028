/**
 * Fetches Bible verse online with Portuguese translation fallback
 */
export async function fetchOnlineVerse(ref: string): Promise<{ text: string; reference?: string } | null> {
  // First check offline dictionary
  const offlineMatch = lookupOfflineVerse(ref);
  if (offlineMatch) {
    return { text: offlineMatch };
  }

  try {
    const normalized = normalizeVerseRef(ref);
    // Find book and chapter:verse
    // Example: "joao 3:16" or "1 corintios 13:4-7"
    let englishQuery = normalized;
    for (const [ptBook, enBook] of Object.entries(BOOK_MAP)) {
      if (normalized.startsWith(ptBook)) {
        englishQuery = normalized.replace(ptBook, enBook);
        break;
      }
    }

    const res = await fetch(`https://bible-api.com/${encodeURIComponent(englishQuery)}?translation=almeida`);
    if (!res.ok) return null;
    
    const data = await res.json();
    if (data && data.text) {
      // Clean up whitespace and line breaks
      const cleanText = data.text.replace(/\s+/g, ' ').trim();
      return { text: cleanText, reference: data.reference };
    }
  } catch (error) {
    console.warn('Erro ao consultar API de Bíblia online:', error);
  }

  return null;
}
